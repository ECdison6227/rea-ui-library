import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const [taskId,status,summary,...sceneIds]=process.argv.slice(2);
const listPath=path.join(root,'docs/remaining-validation.json');
const list=JSON.parse(fs.readFileSync(listPath));
const t=list.tasks.find(t=>t.id===taskId);if(!t)throw Error('Unknown task');
if(!Object.hasOwn(list.statusDefinitions,status))throw Error('Unknown status');
const runId='run03-20261016',base=`evidence/runtime/${runId}`;
const paths=sceneIds.map(id=>`${base}/scenes/${id}/capture.json`);
for(const p of paths)if(!fs.existsSync(path.join(root,p)))throw Error('Missing evidence '+p);
const observation={runId,recordedAt:new Date().toISOString(),summary,evidence:paths};
t.status=status;t.evidence=[...new Set([...t.evidence,...paths])];t.attempts.push(observation);
list.updatedAt=new Date().toISOString();list.status='in_progress';list.currentRun=runId;
fs.writeFileSync(listPath,JSON.stringify(list,null,2)+'\n');
const notesPath=path.join(root,base,'observations.json');
const notes=fs.existsSync(notesPath)?JSON.parse(fs.readFileSync(notesPath)):[];
notes.push({taskId,status,...observation});fs.writeFileSync(notesPath,JSON.stringify(notes,null,2)+'\n');
console.log(JSON.stringify({taskId,status,evidence:paths.length}));
